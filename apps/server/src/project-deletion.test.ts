it('blocks active ledger admissions and concurrent sends while deletion owns the session interlock', async () => {
  const f = await fixture(); await f.attach(session.id); const p = await f.preview();
  let entered!: () => void, release!: () => void;
  const started = new Promise<void>(resolve => { entered = resolve; });
  const pending = new Promise<void>(resolve => { release = resolve; });
  f.client.getSession.mockImplementationOnce(async () => { entered(); await pending; return { session }; });
  const deleting = f.remove(body(p)).then(value => value); await started;
  await expect(f.service.submitRun('fixture-actor', { sessionId: session.id, clientRequestId: 'c17cb7d5-99cf-4a06-a24b-d5d5417e7a7e', input: 'fixture only' })).rejects.toMatchObject({ statusCode: 409 });
  expect(f.client.startRun).not.toHaveBeenCalled(); release(); expect((await deleting).statusCode).toBe(200);
  const g = await fixture(); await g.attach(session.id); const q = await g.preview();
  await g.ledger.append({ action: 'run.requested', actor: 'a'.repeat(64), sessionId: session.id, publicRunId: `jcr_${'b'.repeat(32)}`, clientRequestId: 'c17cb7d5-99cf-4a06-a24b-d5d5417e7a7e', upstreamRunId: null, requestId: null, requestFingerprint: 'b'.repeat(64), outcome: 'requested', status: 'queued', choice: null });
  const refused = await g.remove(body(q)); expect(refused.statusCode).toBe(409); expect(refused.json().error).toContain('Stop active or admitting');
});
it('refuses deletion while a concurrent send is still admitting, without another execution', async () => {
  const f = await fixture(); await f.attach(session.id); const p = await f.preview();
  let enter!: () => void, release!: () => void;
  const started = new Promise<void>(resolve => { enter = resolve; });
  const pending = new Promise<void>(resolve => { release = resolve; });
  f.client.startRun.mockImplementationOnce(async () => { enter(); await pending; return { sessionId: session.id, runId: `run_${'c'.repeat(32)}`, status: 'running', replayed: false }; });
  const send = f.service.submitRun('fixture-actor', { sessionId: session.id, input: 'SYNTHETIC fixture only', clientRequestId: 'c17cb7d5-99cf-4a06-a24b-d5d5417e7a7e' });
  await started;
  expect((await f.remove(body(p))).statusCode).toBe(409);
  release(); await send;
  expect(f.client.startRun).toHaveBeenCalledTimes(1);
  expect((await f.remove(body(p))).statusCode).toBe(409);
});
