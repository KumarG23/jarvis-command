const roots: string[] = [];
const closes: (() => Promise<unknown>)[] = [];
afterEach(async () => { for (const close of closes.splice(0).reverse()) await close(); for (const root of roots.splice(0)) await rm(root, { recursive: true, force: true }); });
const headers = { 'cf-access-jwt-assertion': 'valid', origin: 'https://command.example', 'x-jarvis-command': '1', 'content-type': 'application/json' };
const metadata = { name: 'SYNTHETIC delete fixture', goal: 'Disposable only', repository: '', notes: [] };
const session = { id: `jc_${'a'.repeat(32)}`, title: 'SYNTHETIC retained', source: 'api_server', ownership: 'command', model: null, lastActive: '2026-11-06T12:00:00Z', messageCount: 0, toolCallCount: 0, pinned: false };
const external = { ...session, id: 'discord:fixture', ownership: 'external' };
async function fixture(enabled = true) {
  const root = await mkdtemp(join(tmpdir(), 'jc-project-delete-')); roots.push(root);
  const config = loadConfig({ NODE_ENV: 'test', HERMES_READ_PROXY_KEY: 'r'.repeat(32), COMMAND_MODE: 'enabled', PROJECT_DELETION_MODE: enabled ? 'enabled' : 'disabled', PUBLIC_ORIGIN: headers.origin, HERMES_COMMAND_API_BASE_URL: 'http://127.0.0.1:18643', HERMES_COMMAND_PROXY_KEY: 'c'.repeat(32), COMMAND_AUDIT_LOG_PATH: join(root, 'events.jsonl'), ARTIFACT_STORAGE_PATH: join(root, 'artifacts') });
  const ledger = await AuditLedger.open(config.command!.auditLogPath); closes.push(() => ledger.close());
  const client = { getSession: vi.fn(async (id: string) => ({ session: id === external.id ? external : { ...session, id } })), deleteSession: vi.fn(), startRun: vi.fn(), getRun: vi.fn() };
  const service = createLiveRoomService({ client: client as unknown as CommandProxyClient, ledger });
  const make = (liveRoom = service) => { const app = buildApp({ config, liveRoom, hermes: { readSnapshot: vi.fn() }, verifyAccess: async assertion => { if (assertion !== 'valid') throw Error(); return { subject: 'fixture-actor', provider: 'cloudflare-access' }; } }); closes.push(() => app.close()); return app; };
  const app = make();
  const project = (await app.inject({ method: 'POST', url: '/api/rooms', headers, payload: metadata })).json().room;
  const preview = async () => (await app.inject({ url: `/api/rooms/${project.id}/deletion`, headers })).json();
  const remove = (payload: unknown, override = {}) => app.inject({ method: 'POST', url: `/api/rooms/${project.id}/delete`, headers: { ...headers, ...override }, payload: JSON.stringify(payload) });
  const attach = (id: string) => app.inject({ method: 'POST', url: `/api/rooms/${project.id}/sessions`, headers, payload: { sessionId: id } });
  return { app, root, client, project, preview, remove, attach, make, service, ledger };
}
const body = (preview: { roomId: string; token: string }) => ({ roomId: preview.roomId, token: preview.token, mode: 'project-only' });
it('retains owned/external chats and artifact bytes, snapshots legacy metadata, audits ids and persists detached scopes on restart', async () => {
  const f = await fixture(); await f.attach(session.id); await f.attach(external.id);
  const created = await f.app.inject({ method: 'POST', url: '/api/artifacts/text', headers, payload: { title: 'SYNTHETIC retained artifact', type: 'text', content: 'exact fixture bytes', projectId: f.project.id } });
  expect(created.statusCode).toBe(200);
  const artifact = created.json().artifact;
  const before = await readFile(join(f.root, 'project-rooms.json'));
  const p = await f.preview(); expect(p).toMatchObject({ chats: 2, artifacts: 1, enabled: true, contentsAvailable: false });
  expect(await readFile(join(f.root, 'project-rooms.json'))).toEqual(before);
  expect((await f.remove(body(p))).statusCode).toBe(200);
  expect((await f.remove(body(p))).json()).toEqual({ deleted: true, roomId: f.project.id });
  expect(f.client.deleteSession).not.toHaveBeenCalled();
  const snapshot = (await readdir(f.root)).find(name => name.startsWith('.project-rooms-snapshot-'))!;
  expect((await stat(join(f.root, snapshot))).mode & 0o777).toBe(0o600);
  expect(JSON.parse(await readFile(join(f.root, snapshot), 'utf8')).rooms).toEqual(JSON.parse(before.toString()).rooms);
  await f.app.close(); await f.ledger.close();
  const reopenedLedger = await AuditLedger.open(join(f.root, 'events.jsonl')); closes.push(() => reopenedLedger.close());
  const restarted = f.make(createLiveRoomService({ client: f.client as unknown as CommandProxyClient, ledger: reopenedLedger }));
  expect((await restarted.inject({ url: '/api/rooms', headers })).json().rooms).toEqual([]);
  expect((await restarted.inject({ url: `/api/artifacts/${artifact.id}`, headers })).json().projectId).toBe(null);
  expect((await restarted.inject({ url: `/api/artifacts?projectId=${f.project.id}`, headers })).json().artifacts).toEqual([]);
  expect((await restarted.inject({ url: '/api/artifacts', headers })).json().artifacts.map((a: { id: string }) => a.id)).toContain(artifact.id);
  expect((await restarted.inject({ url: `/api/artifacts/${artifact.id}/versions/1/source`, headers })).json().content).toBe('exact fixture bytes');
  expect((await restarted.inject({ method: 'POST', url: `/api/rooms/${f.project.id}/sessions`, headers, payload: { sessionId: session.id } })).statusCode).toBe(404);
  const audit = await readFile(join(f.root, 'events.jsonl'), 'utf8');
  expect(audit).toContain('project.deleted'); expect(audit).not.toContain(metadata.name); expect(audit).not.toContain('exact fixture bytes');
});
