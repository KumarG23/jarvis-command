  for (const override of [{ origin: 'https://foreign.example' }, { 'cf-access-jwt-assertion': '' }, { 'x-jarvis-command': '' }]) expect((await g.remove(body(p), override)).statusCode).toBeGreaterThanOrEqual(400);
  await g.attach(session.id); expect((await g.remove(body(p))).statusCode).toBe(409);
  expect((await g.app.inject({ url: '/api/rooms', headers })).json().rooms).toHaveLength(1);
  expect((await readdir(g.root)).some(name => name.startsWith('.project-rooms-snapshot-'))).toBe(false);
